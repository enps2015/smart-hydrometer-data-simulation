import pandas as pd
import numpy as np
from datetime import datetime, timedelta
import random

def generate_meter_data_optimized(num_meters, start_date, duration_days, city, region, neighborhoods, user_type_distribution, cultural_events, temperature_range, rainfall_range, pressure_range, output_filename):
    """
    Gera um conjunto de dados simulado para hidrômetros inteligentes para uma única cidade,
    escrevendo os dados diretamente em um arquivo CSV para otimizar o uso da memória.

    Args:
        num_meters (int): O número total de hidrômetros a serem simulados.
        start_date (str): A data de início da simulação, no formato 'YYYY-MM-DD'.
        duration_days (int): A duração da simulação em dias.
        city (str): O nome da cidade para a simulação.
        region (str): A região geográfica da cidade.
        neighborhoods (dict): Dicionário com bairros e suas classes socioeconômicas.
        user_type_distribution (dict): Distribuição de perfis de usuário.
        cultural_events (list): Lista de eventos culturais com datas e bairros afetados.
        temperature_range (tuple): Tupla (min, max) para a temperatura.
        rainfall_range (tuple): Tupla (min, max) para a precipitação.
        pressure_range (tuple): Tupla (min, max) para a pressão.
        output_filename (str): O nome do arquivo de saída.
    """
    # Perfis de consumo em litros por hora (média)
    residential_normal_pattern = np.array([
        0.5, 0.4, 0.3, 0.3, 1.0, 5.0, 8.0, 6.0, 4.0, 3.0, 3.5, 3.0,
        4.0, 4.5, 5.0, 6.0, 8.0, 10.0, 15.0, 12.0, 8.0, 6.0, 5.0, 4.0
    ])

    leak_pattern = residential_normal_pattern + 5
    fraud_pattern = residential_normal_pattern.copy()
    away_pattern = np.array([0.1] * 24)
    commercial_pattern = np.array([
        1.0, 1.0, 1.0, 1.0, 1.5, 3.0, 5.0, 8.0, 10.0, 12.0, 15.0, 18.0,
        20.0, 25.0, 22.0, 18.0, 15.0, 10.0, 8.0, 6.0, 4.0, 3.0, 2.0, 1.5
    ])

    user_patterns = {
        'Residencial Normal': residential_normal_pattern,
        'Residencial com Vazamento': leak_pattern,
        'Residencial com Fraude': fraud_pattern,
        'Residencial em Ausência': away_pattern,
        'Comercial': commercial_pattern
    }

    user_types = list(user_type_distribution.keys())

    # Prepara o cabeçalho do arquivo CSV
    df_header = pd.DataFrame(columns=[
        'timestamp', 'meter_id', 'city', 'region', 'neighborhood',
        'socioeconomic_class', 'user_type', 'consumption_liters',
        'pressure_psi', 'temperature_celsius', 'precipitacao_mm',
        'anomaly_flag', 'evento_cultural_flag'
    ])
    df_header.to_csv(output_filename, mode='w', index=False)

    for i in range(num_meters):
        meter_id = f'{city}_{i:05d}'
        user_type = np.random.choice(user_types, p=list(user_type_distribution.values()))

        neighborhood = random.choice(list(neighborhoods.keys()))
        socioeconomic_class = neighborhoods[neighborhood]

        is_anomaly = False
        if user_type in ['Residencial com Vazamento', 'Residencial com Fraude']:
            is_anomaly = True

        meter_data = []
        current_date = datetime.strptime(start_date, '%Y-%m-%d')
        end_date = current_date + timedelta(days=duration_days)

        while current_date < end_date:
            is_weekend = current_date.weekday() >= 5
            daily_temp = random.uniform(temperature_range[0], temperature_range[1])
            daily_rainfall = random.uniform(rainfall_range[0], rainfall_range[1]) if random.random() < 0.2 else 0
            daily_pressure_base = random.uniform(pressure_range[0], pressure_range[1])
            is_cultural_event = any(current_date >= e['start'] and current_date <= e['end'] for e in cultural_events)

            base_pattern = user_patterns[user_type].copy()

            if is_weekend:
                if user_type == 'Comercial':
                    base_pattern *= 0.2
                elif user_type in ['Residencial Normal', 'Residencial com Vazamento']:
                    base_pattern *= 1.5

            if is_cultural_event:
                event = next((e for e in cultural_events if current_date >= e['start'] and current_date <= e['end']), None)
                if event and neighborhood in event['neighborhoods']:
                    base_pattern *= event['multiplier']

            if user_type == 'Residencial com Vazamento':
                base_pattern += 5

            if user_type == 'Residencial com Fraude':
                if random.random() < 0.1:
                    start_hour = random.randint(0, 23)
                    end_hour = random.randint(start_hour, 23)
                    base_pattern[start_hour:end_hour] = 0.0

            if user_type == 'Residencial em Ausência' and not is_cultural_event:
                if random.random() < 0.95:
                    base_pattern = np.array([0.1] * 24)

            for hour in range(24):
                for quarter in range(4):
                    timestamp = current_date + timedelta(hours=hour, minutes=quarter * 15)
                    consumption = base_pattern[hour] / 4.0 + np.random.normal(0, 0.2)
                    consumption = max(0, consumption)
                    pressure = daily_pressure_base + np.random.normal(0, 0.5)
                    pressure = max(0, pressure)

                    meter_data.append({
                        'timestamp': timestamp,
                        'meter_id': meter_id,
                        'city': city,
                        'region': region,
                        'neighborhood': neighborhood,
                        'socioeconomic_class': socioeconomic_class,
                        'user_type': user_type,
                        'consumption_liters': consumption,
                        'pressure_psi': pressure,
                        'temperature_celsius': daily_temp,
                        'precipitacao_mm': daily_rainfall,
                        'anomaly_flag': is_anomaly,
                        'evento_cultural_flag': is_cultural_event
                    })
            current_date += timedelta(days=1)

        # Cria um DataFrame para este medidor e anexa ao arquivo CSV
        df_meter = pd.DataFrame(meter_data)
        df_meter.to_csv(output_filename, mode='a', header=False, index=False)

    print(f"Dataset de {city} gerado com sucesso e salvo em '{output_filename}'.")


